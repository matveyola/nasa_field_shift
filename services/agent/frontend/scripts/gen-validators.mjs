// Compiles runtime validators for the M0 contracts from the exported JSON Schema.
// Standalone code: no `new Function` at runtime, so the widget works under a strict CSP.
//   npm run gen:validators          write src/widget/contracts/validators.js
//   npm run check:validators        fail if the committed file is out of date
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";
import { _ } from "ajv/dist/compile/codegen/index.js";

const schemaPath = fileURLToPath(new URL("../../contracts/schema/fieldshift-contracts.schema.json", import.meta.url));
const outPath = fileURLToPath(new URL("../src/widget/contracts/validators.js", import.meta.url));
const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
// Proposed service-integration envelopes (M5): the host validates simulation results it fetches.
const integrationPath = fileURLToPath(new URL("../../contracts/schema/fieldshift-integration.schema.json", import.meta.url));
const integration = JSON.parse(readFileSync(integrationPath, "utf8"));

const ajv = new Ajv2020({
  strict: true,
  allErrors: false,
  inlineRefs: false, // one function per $def, shared: keeps the file small
  messages: false, // error text is not shown to anyone; the keyword and path are enough for logs
  code: { source: true, esm: true, formats: _`fullFormats`, lines: false },
});
addFormats(ajv);
ajv.addKeyword("tsType"); // TypeScript generator hint, not a validation rule
ajv.addSchema(schema, "fs");
ajv.addSchema(integration, "fsi");

const exportsMap = {
  validateAgentEvent: "fs#/$defs/AgentEvent",
  validateAgentMessage: "fs#/$defs/AgentMessage",
  validateAgentRequest: "fs#/$defs/AgentRequest",
  validateErrorEnvelope: "fs#/$defs/ErrorEnvelope",
  validateFieldContext: "fs#/$defs/FieldContext",
  validateUIActionEnvelope: "fs#/$defs/UIActionEnvelope",
  validateComparisonResponse: "fsi#/$defs/ComparisonResponse",
  validateFieldProfileResponse: "fsi#/$defs/FieldProfileResponse",
};
const body = standaloneCode(ajv, exportsMap);
const out =
  "// Generated by scripts/gen-validators.mjs from contracts/schema/fieldshift-contracts.schema.json. Do not edit.\n" +
  "/* eslint-disable */\n" +
  'import { fullFormats } from "ajv-formats/dist/formats.js";\n' +
  body
    .replace(/^"use strict";/, "")
    // Ajv's ucs2length counts code points; same result, no CommonJS require in the browser bundle.
    .replace(/const (\w+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;/g, "const $1 = (s) => [...s].length;") +
  "\n";

if (process.argv.includes("--check")) {
  const current = readFileSync(outPath, "utf8");
  if (current !== out) {
    console.error("validators.js is out of date: run npm run gen:validators");
    process.exit(1);
  }
  console.log("validators up to date");
} else {
  writeFileSync(outPath, out);
  console.log(`wrote ${outPath} (${(out.length / 1024).toFixed(0)} KB)`);
}
