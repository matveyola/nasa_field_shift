/** "{n} items" → "3 items". Values are inserted as text; React escapes them on render. */
export function fmt(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (m, k: string) => (k in values ? String(values[k]) : m));
}

/** i18n key → display label; unknown keys fall back to readable words, never to raw ids with dots. */
export function label(d: Dict, key: string): string {
  return d.labels[key] ?? key.split(".").slice(1).join(" ").replace(/_/g, " ");
}
